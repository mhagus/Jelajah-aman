/**
 * Algoritma pencarian lokal fuzzy / substring untuk kota Indonesia
 */
export function cariKotaLokal(kataKunci: string): HasilGeocoding[] {
  const query = kataKunci.trim().toLowerCase();
  if (!query) return [];

  // Filter dan beri skor relevansi
  const hasil = DAFTAR_KOTA_INDONESIA.map((kota) => {
    const namaLower = kota.name.toLowerCase();
    const adminLower = (kota.admin1 ?? "").toLowerCase();

    let skor = 0;
    if (namaLower === query) {
      skor = 100;
    } else if (namaLower.startsWith(query)) {
      skor = 80;
    } else if (namaLower.includes(query)) {
      skor = 60;
    } else if (adminLower.startsWith(query)) {
      skor = 40;
    } else if (adminLower.includes(query)) {
      skor = 30;
    }

    return { kota, skor };
  })
    .filter((item) => item.skor > 0)
    .sort((a, b) => b.skor - a.skor)
    .map((item) => ({
      id: item.kota.id,
      name: item.kota.name,
      latitude: item.kota.latitude,
      longitude: item.kota.longitude,
      country: item.kota.country,
      admin1: item.kota.admin1,
    }));

  return hasil.slice(0, 8);
}

/**
 * Menghasilkan data cuaca & AQI default/estimasi dari dataset lokal
 */
export function dapatkanEstimasiCuacaDanAQI(
  kota: HasilGeocoding | KotaLokal
): { cuaca: DataCuacaLengkap; kualitasUdara: DataKualitasUdara } {
  const dataLokal = DAFTAR_KOTA_INDONESIA.find(
    (k) =>
      k.id === kota.id ||
      k.name.toLowerCase() === kota.name.toLowerCase() ||
      (Math.abs(k.latitude - kota.latitude) < 0.2 &&
        Math.abs(k.longitude - kota.longitude) < 0.2)
  );

  const suhu = dataLokal ? dataLokal.estimasiSuhu : 30;
  const kodeCuaca = dataLokal ? dataLokal.estimasiKodeCuaca : 2;
  const aqi = dataLokal ? dataLokal.estimasiAQI : 50;
  const pm25 = dataLokal ? dataLokal.estimasiPM25 : 12.5;
  const pm10 = dataLokal ? dataLokal.estimasiPM10 : 25.0;

  const hariIni = new Date().toISOString().split("T")[0];

  return {
    cuaca: {
      saatIni: {
        suhu,
        kodeCuaca,
        kecepatanAngin: 12,
        waktu: new Date().toISOString(),
      },
      harian: {
        tanggal: [hariIni],
        suhuMaksimal: [suhu + 2],
        suhuMinimal: [suhu - 4],
        kodeCuaca: [kodeCuaca],
      },
    },
    kualitasUdara: {
      indeksAQI: aqi,
      pm25,
      pm10,
    },
  };
}
